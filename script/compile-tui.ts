import solidPlugin from "@opentui/solid/bun-plugin";

// Package installations live under node_modules, which the host's live TSX
// transformer intentionally excludes. Publish ordinary JS, retaining host imports.
const result = await Bun.build({
  entrypoints: ["src/tui/index.tsx"],
  outdir: "generated",
  naming: "tui.js",
  target: "bun",
  format: "esm",
  packages: "external",
  plugins: [solidPlugin],
  banner: "// Generated by npm run compile:tui. Commit this file with TUI source changes.",
});
if (!result.success) throw new AggregateError(result.logs, "TUI compilation failed");
console.log("Compiled TUI package entrypoint: generated/tui.js");
